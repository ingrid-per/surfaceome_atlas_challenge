"""Step 3a: prepare the FASTA inputs for the topology and signal-peptide tools.

Two outputs:

  data/processed/step3_proteome.fasta   all 20,431 reviewed sequences
  data/processed/step3_pilot.fasta      50 sequences for the pilot run

Selenocysteine (U) is replaced with cysteine (C) because the prediction tools
reject non-standard residues. Only 25 of 20,431 sequences are affected (0.12%)
and every one is listed in results/step3a_sequence_notes.txt, so the
substitution is visible rather than silent.

The pilot is not a random 50. It is every control the later checks depend on,
plus a seeded random remainder — so a broken output parser shows up against
proteins whose answer we already know, before the full run exists.
"""

from __future__ import annotations

import gzip
import random
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
PROC = ROOT / "data" / "processed"
RESULTS = ROOT / "results"

SEED = 20261020  # fixed so the pilot is reproducible

STANDARD = set("ACDEFGHIKLMNPQRSTVWY")

# Controls the Step 3 checks assert on. Positives should be surface, negatives
# must not be, and the GPI set must land in S3 rather than being dropped.
POSITIVE = {"P00533": "EGFR", "P04626": "ERBB2", "P09758": "TACSTD2",
            "Q96NY8": "NECTIN4", "P56747": "CLDN6", "P15391": "CD19",
            "P61769": "B2M"}
GPI_CONTROLS = {"Q13421": "MSLN", "P15328": "FOLR1"}
NEGATIVE = {"P04406": "GAPDH", "P60709": "ACTB", "P68431": "H3C1",
            "P62805": "H4C1", "P0DP23": "CALM1"}


def read_fasta(path: Path):
    """Yield (accession, header, sequence) from the UniProt FASTA."""
    acc_re = re.compile(r"^>\w+\|([^|]+)\|")
    header, chunks = None, []
    with gzip.open(path, "rt") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if header is not None:
                    m = acc_re.match(header)
                    yield (m.group(1) if m else header[1:].split()[0],
                           header, "".join(chunks))
                header, chunks = line, []
            else:
                chunks.append(line)
    if header is not None:
        m = acc_re.match(header)
        yield (m.group(1) if m else header[1:].split()[0], header, "".join(chunks))


def write_fasta(path: Path, records: list[tuple[str, str]], width: int = 60) -> None:
    with path.open("w") as fh:
        for acc, seq in records:
            fh.write(f">{acc}\n")
            for i in range(0, len(seq), width):
                fh.write(seq[i:i + width] + "\n")


def main() -> int:
    PROC.mkdir(parents=True, exist_ok=True)
    RESULTS.mkdir(exist_ok=True)

    records, substituted, empty = [], [], []
    for acc, _header, seq in read_fasta(RAW / "uniprot_human_reviewed.fasta.gz"):
        if not seq:
            empty.append(acc)
            continue
        odd = sorted(set(seq) - STANDARD)
        if odd:
            # U (selenocysteine) -> C. Chemically the closest standard residue
            # and the substitution these tools' own documentation assumes.
            clean = seq.replace("U", "C")
            still = sorted(set(clean) - STANDARD)
            substituted.append({"accession": acc, "characters": "".join(odd),
                                "n_U": seq.count("U"),
                                "unresolved": "".join(still)})
            seq = clean
        records.append((acc, seq))

    write_fasta(PROC / "step3_proteome.fasta", records)

    # ---- pilot ----
    by_acc = dict(records)
    pilot_named = {**POSITIVE, **GPI_CONTROLS, **NEGATIVE}
    pilot = [(a, by_acc[a]) for a in pilot_named if a in by_acc]
    missing = [a for a in pilot_named if a not in by_acc]

    rng = random.Random(SEED)
    pool = sorted(a for a, _ in records if a not in pilot_named)
    for a in rng.sample(pool, 50 - len(pilot)):
        pilot.append((a, by_acc[a]))
    pilot.sort()
    write_fasta(PROC / "step3_pilot.fasta", pilot)

    lengths = [len(s) for _, s in records]
    lines = [
        "STEP 3a — sequence preparation",
        "Generated by src/step3_sequences.py — do not edit by hand.",
        "",
        f"sequences written                        : {len(records):,}",
        f"total residues                           : {sum(lengths):,}",
        f"length min / median / max                : {min(lengths)} / "
        f"{sorted(lengths)[len(lengths) // 2]} / {max(lengths):,}",
        f"empty sequences skipped                  : {len(empty)}",
        "",
        f"sequences with non-standard residues     : {len(substituted)} "
        f"({len(substituted) / len(records):.2%})",
        "  all are selenocysteine (U), replaced with cysteine (C):",
    ]
    for s in substituted:
        flag = "  <-- UNRESOLVED" if s["unresolved"] else ""
        lines.append(f"    {s['accession']}  {s['n_U']} x U{flag}")
    lines += [
        "",
        f"pilot set                                : {len(pilot)} sequences",
        f"  positive controls                      : "
        f"{', '.join(sorted(POSITIVE.values()))}",
        f"  GPI controls (must reach S3)           : "
        f"{', '.join(sorted(GPI_CONTROLS.values()))}",
        f"  negative controls (must be absent)     : "
        f"{', '.join(sorted(NEGATIVE.values()))}",
        f"  random remainder, seed {SEED}      : {50 - len(pilot_named) + len(missing)}",
    ]
    if missing:
        lines.append(f"  WARNING: controls not found in FASTA   : {missing}")

    report = "\n".join(lines)
    print(report)
    (RESULTS / "step3a_sequence_notes.txt").write_text(report + "\n")
    pd.DataFrame(substituted).to_csv(
        RESULTS / "step3a_substituted_residues.csv", index=False)

    print(f"\nWrote data/processed/step3_proteome.fasta ({len(records):,} seqs) "
          f"and step3_pilot.fasta ({len(pilot)} seqs)")
    return 1 if missing or any(s["unresolved"] for s in substituted) else 0


if __name__ == "__main__":
    raise SystemExit(main())
