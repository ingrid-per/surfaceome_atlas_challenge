"""Step 3a: turn UniProt's curated topology annotation into structured records.

This is the *curated* arm of the two-source surface call. The predictor arm
(DeepTMHMM) is the other one; a protein called by both reaches tier S1, by one
only reaches S2 (D20-D22).

UniProt ships topology as semicolon-joined feature strings, e.g.

    TRANSMEM 646..668; /note="Helical"; /evidence="ECO:0000255"
    TOPO_DOM 25..645; /note="Extracellular"; ...
    LIPID 598; /note="GPI-anchor amidated serine"; ...

We parse those into coordinates and derive, per protein:

  * the transmembrane segments
  * the longest SINGLE contiguous extracellular segment (D20 — not the sum,
    because an antibody binds one contiguous region; several short loops
    adding up to 20 residues are not an accessible binding site)
  * whether a signal peptide is annotated, and where (needed later to catch
    the classic TMHMM error of reading a signal peptide as a TM helix)
  * whether a GPI anchor is curated

Writes data/processed/step3_uniprot_topology.csv.
"""

from __future__ import annotations

import csv
import gzip
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
PROC = ROOT / "data" / "processed"
RESULTS = ROOT / "results"

csv.field_size_limit(10**9)

# Positions can carry fuzzy markers: "<1..30", "25..?", "?..645".
POS = r"[<>?]?(\d+|\?)"
TRANSMEM = re.compile(rf"TRANSMEM\s+{POS}\.\.{POS}")
TOPO_DOM = re.compile(rf'TOPO_DOM\s+{POS}\.\.{POS};\s*/note="([^"]+)"')
SIGNAL = re.compile(rf"SIGNAL\s+{POS}\.\.{POS}")
INTRAMEM = re.compile(rf"INTRAMEM\s+{POS}\.\.{POS}")
# UniProt writes GPI anchors as a LIPID feature whose note names the anchor.
LIPID_GPI = re.compile(r'LIPID\s+[<>?]?(\d+);\s*/note="([^"]*GPI-anchor[^"]*)"')


def spans(pattern: re.Pattern, text: str) -> list[tuple[int, int]]:
    """Extract (start, end) pairs, skipping features with unknown endpoints."""
    found = []
    for m in pattern.finditer(text or ""):
        a, b = m.group(1), m.group(2)
        if a == "?" or b == "?":
            continue
        found.append((int(a), int(b)))
    return found


def topo_spans(text: str) -> list[tuple[int, int, str]]:
    """TOPO_DOM features as (start, end, note)."""
    found = []
    for m in TOPO_DOM.finditer(text or ""):
        a, b, note = m.group(1), m.group(2), m.group(3)
        if a == "?" or b == "?":
            continue
        found.append((int(a), int(b), note))
    return found


def main() -> int:
    PROC.mkdir(parents=True, exist_ok=True)
    RESULTS.mkdir(exist_ok=True)

    rows = []
    with gzip.open(RAW / "uniprot_human_reviewed_topology.tsv.gz", "rt") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            tm = spans(TRANSMEM, r["Transmembrane"])
            topo = topo_spans(r["Topological domain"])
            sig = spans(SIGNAL, r["Signal peptide"])
            intra = spans(INTRAMEM, r["Intramembrane"])
            gpi = LIPID_GPI.search(r["Lipidation"] or "")

            # D20: the longest single contiguous extracellular stretch.
            extra = [(b - a + 1) for a, b, note in topo if note == "Extracellular"]
            longest_extra = max(extra) if extra else 0

            rows.append({
                "accession": r["Entry"],
                "symbol": r["Gene Names (primary)"] or "",
                "length": int(r["Length"]) if r["Length"].isdigit() else None,
                "protein_existence": r["Protein existence"],
                "n_tm_segments": len(tm),
                "tm_spans": ";".join(f"{a}-{b}" for a, b in tm),
                "n_extracellular_domains": len(extra),
                "longest_extracellular_len": longest_extra,
                "total_extracellular_len": sum(extra),
                "has_signal_peptide": bool(sig),
                "signal_peptide_end": sig[0][1] if sig else 0,
                "n_intramembrane": len(intra),
                "gpi_curated": bool(gpi),
                "gpi_curated_note": gpi.group(2) if gpi else "",
                "gpi_curated_site": int(gpi.group(1)) if gpi else 0,
                "subcellular_location": (r["Subcellular location [CC]"] or "")[:500],
                "uniprot_surface_call": bool(tm) or bool(gpi),
            })

    df = pd.DataFrame(rows).sort_values("accession", kind="mergesort")
    df.to_csv(PROC / "step3_uniprot_topology.csv", index=False)

    tm_any = df.n_tm_segments > 0
    gpi = df.gpi_curated
    # Proteins with TM segments but no topological domains annotated: UniProt
    # knows they cross the membrane but has not said which side is outside, so
    # their extracellular length is unmeasurable from curation alone.
    tm_no_topo = tm_any & (df.n_extracellular_domains == 0)

    lines = [
        "STEP 3a — UniProt curated topology",
        "Generated by src/step3_uniprot_topology.py — do not edit by hand.",
        "",
        f"proteins parsed                          : {len(df):,}",
        f"  with >=1 transmembrane segment         : {int(tm_any.sum()):,}",
        f"  with a curated GPI anchor              : {int(gpi.sum()):,}",
        f"  UniProt surface call (TM or GPI)       : {int(df.uniprot_surface_call.sum()):,}",
        f"  with a signal peptide                  : {int(df.has_signal_peptide.sum()):,}",
        f"  with intramembrane segments            : {int((df.n_intramembrane > 0).sum()):,}",
        "",
        f"TM proteins with extracellular domains   : {int((tm_any & ~tm_no_topo).sum()):,}",
        f"TM proteins WITHOUT topological domains  : {int(tm_no_topo.sum()):,}",
        "  (UniProt says they cross the membrane but not which side is outside,",
        "   so curation alone cannot measure their extracellular length —",
        "   the predictor arm has to supply it)",
        "",
        "longest extracellular segment, TM proteins with topology:",
    ]
    measurable = df.loc[tm_any & ~tm_no_topo, "longest_extracellular_len"]
    if len(measurable):
        lines += [
            f"  median                                 : {measurable.median():.0f} aa",
            f"  >= 20 aa (the D20 default)             : {int((measurable >= 20).sum()):,}",
            f"  <  20 aa (would be Flagged)            : {int((measurable < 20).sum()):,}",
            f"  >= 10 aa / >= 50 aa (Step 9 grid)      : "
            f"{int((measurable >= 10).sum()):,} / {int((measurable >= 50).sum()):,}",
        ]

    report = "\n".join(lines)
    print(report)
    (RESULTS / "step3a_uniprot_topology.txt").write_text(report + "\n")
    print(f"\nWrote data/processed/step3_uniprot_topology.csv ({len(df):,} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
