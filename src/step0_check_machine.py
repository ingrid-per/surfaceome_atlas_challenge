"""Step 0 check: can this machine actually run the pipeline?

Reports free disk, interpreter and tool versions, and whether each of the six data
hosts answers. Writes docs/step0_machine_report.md and results/step0_machine_report.json
so the figures come from a script, never typed by hand.

Exits non-zero if free disk is below MIN_FREE_GB or any host is unreachable, so a
problem is loud rather than buried in a report nobody reads.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Expression matrices for thousands of samples run to several gigabytes, and Step 1
# pulls six resources. 50 GB is a floor, not a recommendation.
MIN_FREE_GB = 50

# UniProt rejects requests with no User-Agent (403), so every probe sends one.
USER_AGENT = "surface-prot-challenge/0.1 (step0 reachability check)"
HTTP_TIMEOUT = 20

HOSTS = {
    "UniProt REST": "https://rest.uniprot.org/uniprotkb/P00533.json?fields=accession",
    "Human Protein Atlas": "https://www.proteinatlas.org/",
    "UCSC Xena": "https://xenabrowser.net/datapages/",
    "LinkedOmicsKB (CPTAC)": "https://kb.linkedomics.org/",
    "DTU Health Tech (SignalP/DeepTMHMM)": "https://services.healthtech.dtu.dk/",
    "PyPI": "https://pypi.org/simple/",
}

TOOLS = {
    "python": [sys.executable, "--version"],
    "conda": ["conda", "--version"],
    "mamba": ["mamba", "--version"],
    "uv": ["uv", "--version"],
    "git": ["git", "--version"],
}


def tool_version(cmd: list[str]) -> str:
    """First line of `cmd --version`, or a marker if the tool is missing."""
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=30)
    except (FileNotFoundError, subprocess.TimeoutExpired):
        return "NOT AVAILABLE"
    text = (out.stdout or out.stderr).strip()
    return text.splitlines()[0] if text else "NOT AVAILABLE"


def probe(url: str) -> tuple[bool, str]:
    """GET the URL and report the status. Any 2xx/3xx counts as reachable."""
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=HTTP_TIMEOUT) as resp:
            return True, f"HTTP {resp.status}"
    except urllib.error.HTTPError as exc:
        # A 4xx means the host answered. Only 2xx/3xx counts as usable, though.
        return False, f"HTTP {exc.code}"
    except Exception as exc:  # noqa: BLE001 - any network failure is just unreachable
        return False, f"{type(exc).__name__}: {exc}"


def main() -> int:
    usage = shutil.disk_usage(ROOT)
    free_gb = usage.free / 1024**3
    total_gb = usage.total / 1024**3

    tools = {name: tool_version(cmd) for name, cmd in TOOLS.items()}
    tools["python executable"] = sys.executable
    tools["git user.name"] = tool_version(["git", "config", "--get", "user.name"])
    tools["git user.email"] = tool_version(["git", "config", "--get", "user.email"])

    hosts = {name: probe(url) for name, url in HOSTS.items()}

    disk_ok = free_gb >= MIN_FREE_GB
    unreachable = [n for n, (ok, _) in hosts.items() if not ok]
    ok = disk_ok and not unreachable

    report = {
        "date": date.today().isoformat(),
        "project_root": str(ROOT),
        "disk": {
            "free_gb": round(free_gb, 1),
            "total_gb": round(total_gb, 1),
            "minimum_required_gb": MIN_FREE_GB,
            "ok": disk_ok,
        },
        "tools": tools,
        "hosts": {n: {"url": HOSTS[n], "reachable": r, "status": s}
                  for n, (r, s) in hosts.items()},
        "all_checks_passed": ok,
    }

    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "step0_machine_report.json").write_text(
        json.dumps(report, indent=2) + "\n"
    )

    lines = [
        "# Step 0 machine report",
        "",
        f"Generated by `src/step0_check_machine.py` on {report['date']}. "
        "Do not edit by hand — re-run the script.",
        "",
        "## Disk",
        "",
        f"- Free: **{free_gb:.1f} GB** of {total_gb:.1f} GB "
        f"(minimum required: {MIN_FREE_GB} GB) — {'OK' if disk_ok else 'TOO LOW'}",
        "",
        "## Tools",
        "",
        "| Tool | Version |",
        "| --- | --- |",
    ]
    lines += [f"| {n} | {v} |" for n, v in tools.items()]
    lines += [
        "",
        "## Data host reachability",
        "",
        "Probed with a User-Agent header; UniProt returns 403 without one.",
        "",
        "| Host | Status | URL |",
        "| --- | --- | --- |",
    ]
    lines += [
        f"| {n} | {'reachable ' + s if r else '**UNREACHABLE** (' + s + ')'} | {HOSTS[n]} |"
        for n, (r, s) in hosts.items()
    ]
    lines += [
        "",
        "## Verdict",
        "",
        f"**{'All checks passed.' if ok else 'FAILED.'}**",
    ]
    if not disk_ok:
        lines.append(f"- Free disk {free_gb:.1f} GB is below the {MIN_FREE_GB} GB floor.")
    if unreachable:
        lines.append(f"- Unreachable: {', '.join(unreachable)}. "
                     "Download these files yourself and place them in `data/raw/`.")
    lines.append("")

    (ROOT / "docs" / "step0_machine_report.md").write_text("\n".join(lines))

    print("\n".join(lines))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
