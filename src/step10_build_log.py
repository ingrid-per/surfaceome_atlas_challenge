"""Step 10a: build the finalist review log — links only, no judgements.

The runbook makes Step 10 manual on purpose: "You can ask Claude Code to build
the log table and gather the links for you, but not to make the judgments."
So this assembles the table, fills in what the pipeline already knows, and
leaves the verdict columns empty.

Every value here is read from the committed results; nothing is typed.

Writes docs/step10_override_log.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PROC = ROOT / "data" / "processed"
RESULTS = ROOT / "results"
DOCS = ROOT / "docs"

TIER_RANK = {"S1": 0, "S2": 1, "S3": 2, "Flagged": 3}


def accessions() -> dict[str, str]:
    """Ensembl gene -> UniProt accession, by the same route the page uses."""
    c = pd.read_csv(PROC / "surface_candidates.csv")
    c = c[c.is_candidate].drop(columns=["ensembl_gene"])
    gmap = pd.read_csv(PROC / "gene_map.csv", low_memory=False)
    link = (gmap[gmap.accession.isin(set(c.accession))][["accession", "ensembl_gene"]]
            .dropna().drop_duplicates())
    j = link.merge(c, on="accession")
    j["_r"] = j.tier.map(TIER_RANK)
    j = j.sort_values(["ensembl_gene", "_r"], kind="mergesort")
    return dict(zip(j.drop_duplicates("ensembl_gene").ensembl_gene,
                    j.drop_duplicates("ensembl_gene").accession))


def flags(c: dict) -> list[str]:
    """What the pipeline has already raised its hand about, for this gene."""
    f = []
    if c.get("existence") and c["existence"] != "Evidence at protein level":
        f.append(f"**protein existence {c['existence'].lower()}**")
    if c.get("compartment") == "unannotated":
        f.append("compartment unannotated")
    if c.get("frac10") is not None and c["frac10"] < 0.70:
        f.append(f"in {round(c['frac10'] * 100)}% of tumours")
    if c.get("stab") is not None and c["stab"] < 0.75:
        f.append(f"{round(c['stab'] * 100)}% threshold stability")
    if c.get("grade") != "direct":
        f.append(c["grade"].replace("_", " ") + " comparator")
    ecto = c.get("ecto")
    try:
        if ecto is not None and float(ecto) < 50:
            f.append(f"short ectodomain, {ecto} aa")
    except (TypeError, ValueError):
        pass
    return f


def main() -> int:
    d = json.loads((RESULTS / "step7_targets.json").read_text())
    acc = accessions()
    rows = d["top10"] + d["reserve"]

    out = [
        "# Step 10 — finalist review log",
        "",
        "> **Status: in progress.** The table below is generated with every link",
        "> and every flag the pipeline raised; the **Verdict**, **Reason** and",
        "> **Evidence link** columns are filled in by hand and are not yet",
        "> complete. This step is manual on purpose — interpreting antibody",
        "> staining and antibody quality is bench judgement, and it is the part",
        "> the computation cannot supply.",
        "> Regenerate the scaffold with `python src/step10_build_log.py`.",
        "",
        "Generated by `src/step10_build_log.py`. The links and the pipeline's own",
        "flags are filled in; **the verdict, reason and evidence columns are",
        "yours**. The runbook makes this step manual on purpose: interpreting",
        "staining and antibody quality is bench judgment, and it is the part an",
        "AI-only answer cannot supply.",
        "",
        "## What to check, per gene",
        "",
        "1. **Membrane or cytoplasm?** In the HPA images, a surface protein shows",
        "   a rim around each cell. Cytoplasmic filling means it is not a surface",
        "   target however good the RNA looks.",
        "2. **Antibody reliability** — Enhanced > Supported > Approved > Uncertain.",
        "   On an Uncertain antibody the images prove little; say so rather than",
        "   trusting them.",
        "3. **Staining in healthy vital organs** that the bulk RNA averaged away.",
        "4. **Extracellular region** — large enough to bind, and are there",
        "   glycosylation sites in UniProt that could shield the epitope?",
        "5. **Trials or approved drugs**, and any reported toxicity.",
        "6. *Optional:* AlphaFold confidence over the extracellular region. Long,",
        "   disordered and low-confidence is a poor binding site.",
        "",
        "Verdict is **keep**, **drop** or **flag**. If you drop one, promote from",
        "the reserve and note the swap. Every change needs a reason you could say",
        "aloud — you may override the ranking, but never silently.",
        "",
        "## The 15",
        "",
        "| # | Gene | Cancer type | Tier | Ecto | What the pipeline already flags | Links | Verdict | Reason | Evidence link |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]

    for i, c in enumerate(rows, 1):
        g, sym = c["gene"], c["symbol"]
        a = acc.get(g, "")
        hpa = f"https://www.proteinatlas.org/{g}-{sym}"
        links = " · ".join(filter(None, [
            f"[normal]({hpa}/tissue)",
            f"[tumour]({hpa}/pathology)",
            f"[antibody]({hpa}/antibody)",
            f"[UniProt](https://www.uniprot.org/uniprotkb/{a})" if a else "",
            f"[trials](https://clinicaltrials.gov/search?term={sym})",
            f"[AlphaFold](https://alphafold.ebi.ac.uk/entry/{a})" if a else "",
        ]))
        fl = flags(c)
        label = f"{i}" + (" *(res)*" if i > 10 else "")
        out.append(
            f"| {label} | **{sym}** | {c['cancer']} | {c['tier']} | "
            f"{c.get('ecto', '—')} | {'; '.join(fl) if fl else 'none'} | "
            f"{links} |  |  |  |")

    n_flagged = sum(1 for c in rows if flags(c))
    out += [
        "",
        "## Notes",
        "",
        f"- {len(rows)} genes: {len(d['top10'])} finalists and "
        f"{len(d['reserve'])} reserve. {n_flagged} carry at least one flag.",
        "- The reserve is thin. Several reserve genes have lower threshold",
        "  stability than the finalists they would replace, so a swap is not",
        "  automatically an improvement — check the replacement as carefully as",
        "  the gene it replaces.",
        "- Ectodomain length is the longest single extracellular segment (D20);",
        "  `not_applicable` means GPI-anchored, where the whole protein sits",
        "  outside the membrane and the measure does not apply.",
        "",
        "## Swaps",
        "",
        "| Dropped | Promoted from reserve | Reason |",
        "| --- | --- | --- |",
        "|  |  |  |",
    ]

    path = DOCS / "step10_override_log.md"
    path.write_text("\n".join(out) + "\n")
    print(f"wrote {path.relative_to(ROOT)}  ({len(rows)} genes, {n_flagged} flagged)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
